#!/bin/bash
# ==========================================
# 后端启动诊断脚本
# ==========================================

echo "=========================================="
echo "🔍 后端启动诊断"
echo "=========================================="
echo ""

# 1. 查看 backend.log 最后 100 行
echo "【1/4】查看 backend.log 最后 100 行："
echo "----------------------------------------"
if [ -f backend.log ]; then
    tail -100 backend.log
else
    echo "❌ backend.log 文件不存在"
fi
echo "----------------------------------------"
echo ""

# 2. 检查 Java 进程
echo "【2/4】检查 Java 进程："
echo "----------------------------------------"
ps aux | grep -E "java|jar" | grep -v grep || echo "❌ 未找到 Java 进程"
echo "----------------------------------------"
echo ""

# 3. 检查端口 5000
echo "【3/4】检查端口 5000："
echo "----------------------------------------"
netstat -tlnp | grep 5000 || lsof -i:5000 || echo "❌ 端口 5000 未被占用"
echo "----------------------------------------"
echo ""

# 4. 查看完整的 backend.log（如果文件不大）
echo "【4/4】查看完整的 backend.log："
echo "----------------------------------------"
if [ -f backend.log ]; then
    LINES=$(wc -l < backend.log)
    if [ $LINES -lt 200 ]; then
        cat backend.log
    else
        echo "日志文件较大 ($LINES 行)，显示最后 200 行："
        tail -200 backend.log
    fi
else
    echo "❌ backend.log 文件不存在"
fi
echo "----------------------------------------"
echo ""

echo "=========================================="
echo "诊断完成！"
echo "=========================================="
